"""Regenerate deterministic gzip branches from the adapter's plain assets."""
import gzip
import ast
import hashlib
import json
import re
from pathlib import Path
from check_http_assets import embedded_assets

ROOT=Path(__file__).resolve().parents[1]
ADAPTER=ROOT/'runtime/FLProg_WebUI/src/adapters/FLProgWebUiFlprogNetworkPagedHttp.h'

def bundle_source(assets):
    """Keep the proven script order; CSS and JS stay in Flash, not in a RAM queue."""
    loader=assets['/flprog-webui/controls.js?part=loader']['body']
    order=ast.literal_eval(re.search(r'let p=(\[[^\]]+\])',loader).group(1))
    css=assets['/flprog-webui/app.css']['body']
    parts=['{let s=document.createElement("style");s.textContent='+json.dumps(css,ensure_ascii=False)+';document.head.append(s)}']
    parts += [assets['/flprog-webui/'+path]['body'] for path in order]
    parts += ['document.querySelector("#s").textContent="Ресурсы загружены: 100%. Чтение данных ПЛК…"']
    return ';\n'.join(parts)+';\n'


def write_bundle(assets):
    body=bundle_source(assets)
    raw=body.encode('utf-8');compressed=gzip.compress(raw,compresslevel=9,mtime=0)
    values=', '.join('0x%02x'%v for v in compressed)
    text='''// Generated by build_gzip_assets.py. Stream directly from Flash.
#pragma once
#include "FLProgWebUiGzipHttp.h"
#if defined(FLPROG_HTTP_SERVER_HAS_FLASH_STREAM)
inline void flprogWebUiSendBundle(FLProgNetworkHttpServer *server)
{
#if FLPROG_WEBUI_GZIP_ASSETS
    static const unsigned char data[] PROGMEM = {'''+values+'''};
    flprogWebUiSendGzip(server, "application/javascript", data, sizeof(data));
#else
    static const char data[] PROGMEM = '''+json.dumps(body,ensure_ascii=False)+''';
    flprogWebUiSendIdentity(server, "application/javascript", data);
#endif
}
#endif
'''
    (ADAPTER.parent/'FLProgWebUiBundle.h').write_text(text,encoding='utf-8')
    # The temporary-adapter tests must not modify the checkout's readable file.
    if ADAPTER==ROOT/'runtime/FLProg_WebUI/src/adapters/FLProgWebUiFlprogNetworkPagedHttp.h':
        (ROOT/'runtime/FLProg_WebUI/web_assets/bundle.js').write_text(body,encoding='utf-8')
    return dict(raw=len(raw),gzip=len(compressed),sha256=hashlib.sha256(raw).hexdigest())

def generate():
    text=ADAPTER.read_text(encoding='utf-8')
    text=re.sub(r'#if FLPROG_WEBUI_GZIP_ASSETS\n.*?\n#else\n', '', text, flags=re.S)
    text=text.replace('\n#endif // FLPROG_WEBUI_GZIP_ASSETS','')
    assets,_=embedded_assets(ADAPTER)
    normalized={k:re.sub(r'webui175-[0-9a-f]{12}', 'webui175-VERSION',v['body']) for k,v in assets.items()}
    normalized['flash_bundle']=bundle_source(assets)
    version='webui175-'+hashlib.sha256(json.dumps(normalized,sort_keys=True,ensure_ascii=False).encode('utf-8')).hexdigest()[:12]
    text=re.sub(r'webui175-[0-9a-f]{12}',version,text)
    ADAPTER.write_text(text,encoding='utf-8')
    assets,_=embedded_assets(ADAPTER)
    bundle=write_bundle(assets)
    (ADAPTER.parent/'FLProgWebUiAssetVersion.h').write_text('#pragma once\n#define FLPROG_WEBUI_ASSET_VERSION "'+version+'"\n',encoding='utf-8')
    pattern=r'(static void FLPROG_WEBUI_HTTP_FLASH (\w+)\(FLProgNetworkHttpServer \*value\)\s*\{.*?)(static const char asset\[\] PROGMEM =.*?flprogWebUiSendIdentity\(value, "([^"]+)", asset\);)'
    callbacks=dict((callback,path) for path,callback in re.findall(r'server.addHandler\("([^"]+)",\s*(\w+),',text))
    callbacks.update(re.findall(r'// asset-route: (\w+) (\S+)',text))
    measurements={}
    def replace(m):
        path=callbacks[m[2]];raw=assets[path]['body'].encode('utf-8')
        compressed=gzip.compress(raw,compresslevel=9,mtime=0)
        assert gzip.decompress(compressed)==raw
        header=('HTTP/1.1 200 OK\r\nContent-Type: '+m[4]+'\r\nContent-Encoding: gzip\r\nVary: Accept-Encoding\r\nContent-Length: '+str(len(compressed))+'\r\nConnection: close\r\n\r\n').encode()
        assert len(header)+len(compressed)<=2048
        values=', '.join('0x%02x'%v for v in compressed)
        branch='#if FLPROG_WEBUI_GZIP_ASSETS\n        static const unsigned char assetGzip[] PROGMEM = {'+values+'};\n        static_assert(sizeof(assetGzip) + 192U <= FLPROG_HTTP_SERVER_MAX_RESPONSE_BYTES, "gzip response budget");\n        flprogWebUiSendGzip(value, "'+m[4]+'", assetGzip, sizeof(assetGzip));\n#else\n        '
        measurements[path]=dict(raw=len(raw),gzip=len(compressed),http_bytes=len(header)+len(compressed),sha256=hashlib.sha256(raw).hexdigest())
        return m[1]+branch+m[3]+'\n#endif // FLPROG_WEBUI_GZIP_ASSETS'
    text,count=re.subn(pattern,replace,text,flags=re.S)
    assert count==len(assets),(count,len(assets))
    if '#include "FLProgWebUiGzipHttp.h"' not in text:
        text=text.replace('#include <flprogNetwork.h>','#include <flprogNetwork.h>\n#include "FLProgWebUiGzipHttp.h"')
    ADAPTER.write_text(text,encoding='utf-8')
    measurements['flash_bundle']=bundle
    return measurements

if __name__=='__main__':print(json.dumps(generate(),ensure_ascii=False,indent=2))
