#!/usr/bin/env python3
"""Minimal local server for the FLProg Web UI Designer prototype.

The editor intentionally has no external Python or JavaScript dependencies.
It stores .flpui projects only in the adjacent projects directory, avoiding an
accidental write to an arbitrary Windows path from the browser.
"""

from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, quote, urlparse
import json
import re
import sys
import uuid
from xml.sax.saxutils import escape as xml_escape

ROOT = Path(__file__).resolve().parent
PROJECTS = ROOT / "projects"
EXPORTS = ROOT / "exports"
LIBRARY_PROJECT_HEADER = Path(r"C:\FL\FLProg_9.8.1_Windows_Portable\ideV8\portable\sketchbook\libraries\FLProg_Network\src\flprogWebUiProject.h")
PROJECTS.mkdir(exist_ok=True)
EXPORTS.mkdir(exist_ok=True)


def project_file(name: str) -> Path:
    """Return a safe local project path, rejecting directory traversal."""
    stem = re.sub(r"[^A-Za-zА-Яа-я0-9_.-]+", "_", name).strip("._") or "webui_project"
    if stem.lower().endswith(".flpui"):
        stem = stem[:-6]
    return PROJECTS / (stem + ".flpui")


def c_string(value) -> str:
    """Encode a UTF-8 JSON value safely as a C string literal."""
    return json.dumps(str(value), ensure_ascii=False)


def generated_header(document: dict) -> str:
    """Generate the stable editor-to-runtime descriptor; no Arduino JSON needed."""
    project = document.get("project", {})
    rows = []
    for page in document.get("pages", []):
        page_id = page.get("id", "main")
        for item in page.get("widgets", []):
            binding = item.get("binding", {})
            rows.append((page_id, item.get("id", "widget"), item.get("type", "text"),
                         item.get("label", ""), binding.get("read", ""), binding.get("write", "")))
    lines = [
        "// Generated by FLProg Web UI Designer. Do not edit manually.",
        "#pragma once",
        "#include <flprogNetwork.h>",
        "",
        "#define FLPROG_WEBUI_SCHEMA_VERSION \"flprog.webui/0.1\"",
        "#define FLPROG_WEBUI_PROJECT_TITLE " + c_string(project.get("title", "FLProg Web UI")),
        "#define FLPROG_WEBUI_DEVICE_PROFILE " + c_string(project.get("deviceProfile", "unknown")),
        "",
        "static const FLProgWebUiWidgetDescriptor flprogWebUiWidgets[] = {",
    ]
    for row in rows:
        lines.append("    {" + ", ".join(c_string(v) for v in row) + "},")
    lines += [
        "};",
        "static const uint16_t flprogWebUiWidgetCount = " + str(len(rows)) + ";",
        "",
    ]
    return "\n".join(lines)


def fvl_xml(document: dict) -> str:
    """Build a FLProg variable-library XML document from widget bindings."""
    # These are FLProg's data-type class names.  In particular, a slider is an
    # IntegerDataType, not an Arduino/C++ ``long`` spelling.
    type_by_widget = {"switch": "BooleanDataType", "slider": "IntegerDataType",
                      "indicator": "FloatDataType", "text": "StringDataType"}
    channels = []
    by_name = {}
    for page in document.get("pages", []):
        for item in page.get("widgets", []):
            value_type = type_by_widget.get(item.get("type"), "StringDataType")
            binding = item.get("binding", {})
            for mode, name in (("read", binding.get("read", "")), ("write", binding.get("write", ""))):
                name = str(name).strip()
                if not name:
                    continue
                channel = by_name.get(name)
                if channel is None:
                    channel = {"name": name, "type": value_type, "read": False,
                               "write": False, "label": str(item.get("label") or name)}
                    by_name[name] = channel
                    channels.append(channel)
                elif channel["type"] != value_type:
                    raise ValueError(f'Канал "{name}" используется с несовместимыми типами')
                channel[mode] = True
    rows = ['<sixx.object sixx.id="0" sixx.type="OrderedCollection" sixx.env="Core">']
    for index, channel in enumerate(channels, 1):
        name, value_type = channel["name"], channel["type"]
        base = index * 10
        safe_name = xml_escape(name)
        variable_id = str(uuid.uuid5(uuid.NAMESPACE_URL, "flprog-webui/" + name))
        if value_type == "BooleanDataType":
            default_xml = '    <sixx.object sixx.name="defaulValue" sixx.type="False" sixx.env="Core"/>'
        elif value_type == "StringDataType":
            default_xml = '    <sixx.object sixx.name="defaulValue" sixx.type="String" sixx.env="Core"></sixx.object>'
        else:
            # FLProg stores a numeric default as a SmallInteger object.  It is
            # valid for both IntegerDataType and FloatDataType (as in native
            # FLProg projects); ``sixx.type=\"0\"`` is not a valid object type.
            default_xml = '    <sixx.object sixx.name="defaulValue" sixx.type="SmallInteger" sixx.env="Core">0</sixx.object>'
        rows += [
            f'  <sixx.object sixx.id="{base}" sixx.type="FBDVariableTag" sixx.env="Arduino">',
            f'    <sixx.object sixx.id="{base + 1}" sixx.name="id" sixx.type="String" sixx.env="Core">{variable_id}</sixx.object>',
            f'    <sixx.object sixx.id="{base + 2}" sixx.name="comment" sixx.type="String" sixx.env="Core">FLProg Web UI</sixx.object>',
            '    <sixx.object sixx.name="isGlobal" sixx.type="True" sixx.env="Core"/>',
            f'    <sixx.object sixx.id="{base + 3}" sixx.name="name" sixx.type="String" sixx.env="Core">{safe_name}</sixx.object>',
            f'    <sixx.object sixx.id="{base + 4}" sixx.name="type" sixx.type="{value_type} class" sixx.env="Arduino"><sixx.object sixx.id="{base + 5}" sixx.name="instanceCollection" sixx.type="OrderedCollection" sixx.env="Core"><sixx.object sixx.id="{base + 6}" sixx.type="{value_type}" sixx.env="Arduino"/><sixx.object sixx.idref="{base + 6}"/></sixx.object></sixx.object>',
            f'    <sixx.object sixx.id="{base + 7}" sixx.name="bitNumber" sixx.type="SmallInteger" sixx.env="Core">1</sixx.object>',
            default_xml,
            '    <sixx.object sixx.name="isSaveToEeprom" sixx.type="False" sixx.env="Core"/>',
            f'    <sixx.object sixx.id="{base + 8}" sixx.name="maximumLineLengt" sixx.type="SmallInteger" sixx.env="Core">20</sixx.object>',
            '  </sixx.object>',
        ]
    rows.append('</sixx.object>')
    return "\r\n".join(rows) + "\r\n"


def webui_channels(document: dict) -> list:
    """Return the ordered, type-checked channel model used by all exports."""
    type_by_widget = {"switch": "BooleanDataType", "slider": "IntegerDataType",
                      "indicator": "FloatDataType", "text": "StringDataType"}
    channels, by_name = [], {}
    for page in document.get("pages", []):
        for item in page.get("widgets", []):
            value_type = type_by_widget.get(item.get("type"), "StringDataType")
            for mode in ("read", "write"):
                name = str(item.get("binding", {}).get(mode, "")).strip()
                if not name:
                    continue
                channel = by_name.get(name)
                if channel is None:
                    channel = {"name": name, "type": value_type, "read": False,
                               "write": False, "label": str(item.get("label") or name)}
                    by_name[name] = channel
                    channels.append(channel)
                elif channel["type"] != value_type:
                    raise ValueError(f'Канал "{name}" используется с несовместимыми типами')
                channel[mode] = True
    return channels


def ubi_xml(document: dict) -> str:
    """Build one typed FLProg user block for this Web UI project."""
    channels = webui_channels(document)
    title = str(document.get("project", {}).get("title", "Web UI"))
    block_id = str(uuid.uuid5(uuid.NAMESPACE_URL, "flprog-webui-block/" + title))
    used_pins = set()

    def pin_name(channel, index):
        stem = re.sub(r"[^A-Za-z0-9_]+", "_", channel["name"]).strip("_") or f"CHANNEL_{index}"
        stem = stem.upper()
        candidate = stem
        suffix = 2
        while candidate in used_pins:
            candidate = f"{stem}_{suffix}"
            suffix += 1
        used_pins.add(candidate)
        return candidate

    for index, channel in enumerate(channels, 1):
        channel["pin"] = pin_name(channel, index)

    object_id = 10
    def next_id():
        nonlocal object_id
        value = object_id
        object_id += 1
        return value

    def io_element(name, data_type, is_input, comment):
        adaptor, adaptor_uid, obj, obj_uid, typ, label, note = [next_id() for _ in range(7)]
        direction = "True" if is_input else "False"
        cache = '' if is_input else f'<sixx.object sixx.name="nameCash" sixx.idref="{label}"/>'
        return (f'<sixx.object sixx.id="{adaptor}" sixx.type="InputsOutputsAdaptorForUserBlock" sixx.env="Arduino">'
                f'<sixx.object sixx.id="{adaptor_uid}" sixx.type="String" sixx.env="Core" sixx.name="id">{uuid.uuid4()}</sixx.object>'
                f'<sixx.object sixx.id="{obj}" sixx.type="UniversalBlockInputOutput" sixx.env="Arduino" sixx.name="object">'
                f'<sixx.object sixx.id="{obj_uid}" sixx.type="String" sixx.env="Core" sixx.name="id">{uuid.uuid4()}</sixx.object>'
                f'<sixx.object sixx.name="block" sixx.idref="1"/>'
                f'<sixx.object sixx.id="{typ}" sixx.type="{data_type}" sixx.env="Arduino" sixx.name="type"/>'
                f'<sixx.object sixx.name="isInput" sixx.type="{direction}" sixx.env="Core"/>'
                f'<sixx.object sixx.id="{label}" sixx.type="String" sixx.env="Core" sixx.name="name">{xml_escape(name)}</sixx.object>'
                f'<sixx.object sixx.name="isNot" sixx.type="False" sixx.env="Core"/>{cache}</sixx.object>'
                f'<sixx.object sixx.id="{note}" sixx.type="String" sixx.env="Core" sixx.name="comment">{xml_escape(comment)}</sixx.object>'
                f'</sixx.object>')

    inputs = [io_element("EN", "BooleanDataType", True, "Разрешение работы Web UI")]
    for channel in channels:
        inputs.append(io_element(channel["pin"], channel["type"], True,
                                 "Web UI: " + channel["label"]))
    outputs = []
    for channel in channels:
        if channel["write"]:
            outputs.append(io_element("NEW_" + channel["pin"], "BooleanDataType", False,
                                      "Новая команда Web UI: " + channel["label"]))
            outputs.append(io_element("VALUE_" + channel["pin"], channel["type"], False,
                                      "Значение из Web UI: " + channel["label"]))

    loop = []
    for channel in channels:
        loop.append(f'if (EN) flpWebUiBlocks().setValue({c_string(channel["name"])}, {channel["pin"]});')
    for channel in channels:
        if not channel["write"]:
            continue
        pin = channel["pin"]
        loop.append(f'NEW_{pin} = false;')
        loop.append(f'if (EN && flpWebUiBlocks().takeWrite({c_string(channel["name"])}, VALUE_{pin})) NEW_{pin} = true;')
    loop_code = xml_escape("\n".join(loop))
    info = ("Сгенерированный блок проекта Web UI. Входы публикуют значения в браузер; "
            "выходы NEW_*/VALUE_* передают действия пользователя в FBD-схему.")
    return ('<?xml version="1.0" encoding="utf-16"?>\r\n'
            f'<sixx.object sixx.id="0" sixx.type="BlocksLibraryElement" sixx.env="Arduino">'
            f'<sixx.object sixx.id="1" sixx.type="CodeUserBlock" sixx.env="Arduino" sixx.name="typeClass">'
            f'<sixx.object sixx.id="2" sixx.type="String" sixx.env="Core" sixx.name="id">{block_id}</sixx.object>'
            f'<sixx.object sixx.id="3" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="blocks"/>'
            f'<sixx.object sixx.id="4" sixx.type="String" sixx.env="Core" sixx.name="label">Web UI: {xml_escape(title)}</sixx.object>'
            f'<sixx.object sixx.id="5" sixx.type="String" sixx.env="Core" sixx.name="name">Web UI: {xml_escape(title)}</sixx.object>'
            f'<sixx.object sixx.id="6" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="inputs">{"".join(inputs)}</sixx.object>'
            f'<sixx.object sixx.id="7" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="outputs">{"".join(outputs)}</sixx.object>'
            f'<sixx.object sixx.id="8" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="variables"/>'
            f'<sixx.object sixx.id="9" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="parametrs"/>'
            f'<sixx.object sixx.id="9001" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="userLibraries"/>'
            f'<sixx.object sixx.id="9002" sixx.type="String" sixx.env="Core" sixx.name="info">{xml_escape(info)}</sixx.object>'
            f'<sixx.object sixx.id="9003" sixx.type="CodeUserBlockLoopCodePart" sixx.env="Arduino" sixx.name="loopCodePart"><sixx.object sixx.id="9004" sixx.type="String" sixx.env="Core" sixx.name="code">{loop_code}</sixx.object></sixx.object>'
            f'<sixx.object sixx.id="9005" sixx.type="CodeUserBlockSetupCodePart" sixx.env="Arduino" sixx.name="setupCodePart"><sixx.object sixx.id="9006" sixx.type="String" sixx.env="Core" sixx.name="code"/></sixx.object>'
            f'<sixx.object sixx.id="9007" sixx.type="CodeUserBlockDeclareCodePart" sixx.env="Arduino" sixx.name="declareCodePart"><sixx.object sixx.id="9008" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="code"><sixx.object sixx.id="9009" sixx.type="CodeUserBlockDeclareDefineBlock" sixx.env="Arduino"><sixx.object sixx.id="9010" sixx.type="String" sixx.env="Core" sixx.name="define">#include</sixx.object><sixx.object sixx.id="9011" sixx.type="String" sixx.env="Core" sixx.name="name">&lt;flprogWebUiUserBlocks.h&gt;</sixx.object></sixx.object></sixx.object></sixx.object>'
            f'<sixx.object sixx.id="9012" sixx.type="CodeUserBlockFunctuinCodePart" sixx.env="Arduino" sixx.name="functionCodePart"><sixx.object sixx.id="9013" sixx.type="OrderedCollection" sixx.env="Core" sixx.name="code"/></sixx.object>'
            f'<sixx.object sixx.name="notCanManyUse" sixx.type="False" sixx.env="Core"/>'
            f'</sixx.object></sixx.object>\r\n')


class DesignerHandler(SimpleHTTPRequestHandler):
    def __init__(self, *args, **kwargs):
        super().__init__(*args, directory=str(ROOT / "public"), **kwargs)

    def log_message(self, fmt, *args):
        print("[WebUI] " + fmt % args)

    def send_json(self, status, data):
        payload = json.dumps(data, ensure_ascii=False, indent=2).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)

    def do_GET(self):
        request = urlparse(self.path)
        if request.path == "/api/projects":
            names = sorted(p.name for p in PROJECTS.glob("*.flpui"))
            return self.send_json(200, {"projects": names})
        if request.path == "/api/project":
            name = parse_qs(request.query).get("name", ["demo.flpui"])[0]
            path = project_file(name)
            if not path.exists():
                return self.send_json(404, {"error": "Проект не найден"})
            try:
                return self.send_json(200, json.loads(path.read_text(encoding="utf-8")))
            except (OSError, json.JSONDecodeError) as error:
                return self.send_json(500, {"error": str(error)})
        if request.path == "/api/download-fvl":
            name = parse_qs(request.query).get("name", ["webui_project"])[0]
            path = EXPORTS / (project_file(name).stem + ".fvl")
            if not path.exists():
                return self.send_json(404, {"error": "Файл экспорта ещё не создан"})
            try:
                payload = path.read_bytes()
                self.send_response(200)
                self.send_header("Content-Type", "application/xml; charset=utf-16")
                self.send_header("Content-Disposition", f'attachment; filename="{path.name}"')
                self.send_header("Content-Length", str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)
                return
            except OSError as error:
                return self.send_json(500, {"error": str(error)})
        if request.path == "/api/download-ubi":
            name = parse_qs(request.query).get("name", ["webui_project"])[0]
            path = EXPORTS / (project_file(name).stem + ".ubi")
            if not path.exists():
                return self.send_json(404, {"error": "Файл блока ещё не создан"})
            try:
                payload = path.read_bytes()
                self.send_response(200)
                self.send_header("Content-Type", "application/xml; charset=utf-16")
                self.send_header("Content-Disposition", f'attachment; filename="{path.name}"')
                self.send_header("Content-Length", str(len(payload)))
                self.end_headers()
                self.wfile.write(payload)
                return
            except OSError as error:
                return self.send_json(500, {"error": str(error)})
        return super().do_GET()

    def do_POST(self):
        endpoint = urlparse(self.path).path
        if endpoint not in ("/api/project", "/api/export", "/api/install", "/api/export-fvl", "/api/export-ubi"):
            return self.send_json(404, {"error": "Неизвестный API"})
        try:
            length = int(self.headers.get("Content-Length", "0"))
            document = json.loads(self.rfile.read(length).decode("utf-8"))
            if document.get("schema") != "flprog.webui/0.1":
                raise ValueError("Ожидается schema: flprog.webui/0.1")
            name = str(document.get("project", {}).get("fileName", "webui_project"))
            if endpoint == "/api/project":
                path = project_file(name)
                path.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
                return self.send_json(200, {"ok": True, "file": path.name})
            header = generated_header(document)
            widgets = sum(len(p.get("widgets", [])) for p in document.get("pages", []))
            if endpoint == "/api/export-fvl":
                path = EXPORTS / (project_file(name).stem + ".fvl")
                # FLProg's .fvl reference format is UTF-16 little-endian with BOM.
                path.write_bytes(b"\xff\xfe" + fvl_xml(document).encode("utf-16-le"))
                return self.send_json(200, {"ok": True, "file": path.name,
                                            "variables": fvl_xml(document).count('sixx.type="FBDVariableTag"'),
                                            "download": "/api/download-fvl?name=" + quote(name)})
            if endpoint == "/api/export-ubi":
                path = EXPORTS / (project_file(name).stem + ".ubi")
                # FLProg's native user blocks are UTF-16LE with BOM and an XML
                # declaration. UTF-8 otherwise displays Russian labels as mojibake.
                path.write_bytes(b"\xff\xfe" + ubi_xml(document).encode("utf-16-le"))
                return self.send_json(200, {"ok": True, "file": path.name,
                                            "channels": len(webui_channels(document)),
                                            "download": "/api/download-ubi?name=" + quote(name)})
            if endpoint == "/api/export":
                path = EXPORTS / (project_file(name).stem + "_generated.h")
                path.write_text(header, encoding="utf-8")
                return self.send_json(200, {"ok": True, "file": path.name, "widgets": widgets})
            LIBRARY_PROJECT_HEADER.write_text(header, encoding="utf-8")
            return self.send_json(200, {"ok": True, "file": str(LIBRARY_PROJECT_HEADER), "widgets": widgets})
        except (ValueError, OSError, json.JSONDecodeError) as error:
            return self.send_json(400, {"ok": False, "error": str(error)})


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8765
    server = ThreadingHTTPServer(("127.0.0.1", port), DesignerHandler)
    print(f"FLProg Web UI Designer: http://127.0.0.1:{port}")
    print(f"Projects: {PROJECTS}")
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nDesigner stopped")
    finally:
        server.server_close()


if __name__ == "__main__":
    main()
